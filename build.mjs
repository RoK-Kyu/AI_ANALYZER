// TextLens build script. No npm packages needed, only Node.js 18 or newer.
//
//   node build.mjs           -> builds the site into ./dist
//   node build.mjs --serve   -> builds, then serves ./dist at http://localhost:5173
//
// The Gemini key comes from the GEMINI_API_KEY environment variable (used by
// GitHub Actions) or, if that is not set, from the .env file in this folder.

import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync, existsSync, statSync } from 'node:fs';
import { createServer } from 'node:http';
import { join, extname, normalize, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const dist = join(root, 'dist');

function readDotEnv() {
  const file = join(root, '.env');
  if (!existsSync(file)) return {};
  const out = {};
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!m || line.trim().startsWith('#')) continue;
    out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2').trim();
  }
  return out;
}

const dotenv = readDotEnv();
const pick = name => (process.env[name] || dotenv[name] || '').trim();
let key = pick('GEMINI_API_KEY');
if (/^paste-your|^your-|^$/i.test(key)) key = '';
const model = pick('GEMINI_MODEL');

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
cpSync(join(root, 'index.html'), join(dist, 'index.html'));
cpSync(join(root, 'src'), join(dist, 'src'), { recursive: true });
writeFileSync(join(dist, '.nojekyll'), '');
writeFileSync(join(dist, 'config.js'),
  `// Generated by build.mjs. Do not edit or commit.\nexport default ${JSON.stringify({ GEMINI_API_KEY: key, GEMINI_MODEL: model }, null, 2)};\n`);

console.log(`Built TextLens into dist/  (Gemini key: ${key ? 'found' : 'NOT set, the app will ask for one'}${model ? `, model: ${model}` : ''})`);

if (process.argv.includes('--serve')) {
  const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.json': 'application/json', '.png': 'image/png' };
  const port = Number(process.env.PORT) || 5173;
  createServer((req, res) => {
    let p = normalize(decodeURIComponent(req.url.split('?')[0])).replace(/^(\.\.[\/\\])+/, '');
    let file = join(dist, p);
    if (existsSync(file) && statSync(file).isDirectory()) file = join(file, 'index.html');
    if (!file.startsWith(dist) || !existsSync(file)) { res.writeHead(404); res.end('Not found'); return; }
    res.writeHead(200, { 'Content-Type': types[extname(file)] || 'application/octet-stream' });
    res.end(readFileSync(file));
  }).listen(port, () => console.log(`TextLens is running at http://localhost:${port}  (press Ctrl+C to stop)`));
}
